local out=assert(os.getenv('TMC_TEST_OUTPUT'))
local H=assert(loadfile(out..'../../build/regions/EU/tests/gameplay_harness.lua'))()
H.run(function()
 local expected=assert(tonumber(out:match('language_(%d+)')))
 H.check(H.r8(0x2000007)==expected,'native regional language selected from EEPROM')
 H.shot('native_gameplay')
 H.press(8);H.wait(65);H.shot('native_inventory')
 local vram=emu:readRange(0x6000000,0x18000)
 H.menu(13,0);H.shot('practice_over_native_inventory')
 H.check(H.r8(H.PM+H.L.modalMode)==1,'Practice modal opens over localized inventory')
 H.press(H.hotkey());H.wait(12)
 H.check(H.r8(H.PM+H.L.modalMode)==0 and emu:readRange(0x6000000,0x18000)==vram,'localized inventory graphics restored exactly')
 H.shot('inventory_restored');H.press(8);H.wait(80)
 H.warp(3,1,336,272)
 for i=1,300 do if (H.r8(0x2000050)&0x7F)~=0 then break end;H.wait(1) end
 H.check((H.r8(0x2000050)&0x7F)~=0,'native localized story text opens')
 H.wait(55);H.shot('localized_dialog')
 local id=H.r16(0x2000054);H.menu(12,0);H.shot('practice_over_dialog');H.close()
 H.check(H.r16(0x2000054)==id and (H.r8(0x2000050)&0x7F)~=0,'localized conversation survives Practice')
 H.wait(20);H.shot('dialog_restored')
 H.check(H.r8(0x2000007)==expected,'Practice never changes native language')
end)
