local out=assert(os.getenv('TMC_TEST_OUTPUT'))
local H=assert(loadfile(out..'../../tests/gameplay_harness.lua'))()
H.run(function()
 local state=emu:saveStateBuffer()
 -- Drive the real native parser with Stockwell's shield purchase text.
 -- This fixture requests a message; it does not fabricate a choice state.
 H.log('FIXTURE native MessageRequest structure: Stockwell shield purchase 2C02')
 for i=0,31 do emu:write8(0x2000050+i,0) end
 emu:write16(0x2000058,0x2C02);emu:write8(0x2000052,99)
 emu:write8(0x2000054,26);emu:write8(0x2000055,4)
 emu:write8(0x2000056,1);emu:write8(0x2000057,12);emu:write8(0x2000050,1)
 H.wait(12);H.menu(1,10);H.press(1);H.close();H.wait(160);H.shot('skip_stops_at_native_choice')
 H.log(string.format('choice count=%d render=%d message=%d result=%d',H.r8(0x2024032),H.r8(0x2022809),H.r8(0x2000050),H.r8(0x2000040)))
 H.check(H.r16(H.PM+H.L.sceneSkipTicks)==0,'fast skip stops at native choice')
 H.check(H.r8(0x2024032)==2 and H.r8(0x2022809)==5,'native yes/no enquiry remains on screen')
 H.check(H.r8(0x2000040)~=3,'skip has not confirmed either choice')
 H.menu(1,10);H.press(1)
 H.check(H.r8(H.PM+13)==1,'starting skip on paused choice is rejected')
 H.close();H.wait(20);H.press(0x10);H.press(1);H.wait(100)
 H.check(H.r8(0x2000040)==3 and H.r8(0x2024032)==0,'user can answer restored choice normally')
 emu:loadStateBuffer(state);H.wait(3)
 H.warp(3,1,336,272);H.menu(1,10);H.press(1)
 H.wait(2,2);H.wait(60)
 H.check(H.r16(H.PM+H.L.sceneSkipTicks)==0,'B cancels armed/running skip')
 H.check(emu:readRange(H.PM+H.L.status,28):find('CANCELLED')~=nil,'B uses explicit cancellation path')
end)
