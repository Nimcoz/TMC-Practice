local out=assert(os.getenv('TMC_TEST_OUTPUT'))
local H=assert(loadfile(out..'../../tests/gameplay_harness.lua'))()
H.run(function()
 H.menu(13,4);H.press(0x10);H.press(0x10)
 H.menu(13,5);H.press(1);H.wait(60);H.close()
 local name=emu:readRange(0x2002AC0,6);local slot=H.r8(0x2000004)
 local before=emu:readRange(0x2002A40,0x4B4)
 H.menu(16,10);H.press(1);H.shot('confirmation_default_cancel')
 H.check(H.r8(H.PM+H.L.page)==22 and H.r8(H.PM+H.L.cursor+22)==0,'100% opens on CANCEL')
 H.press(1);H.check(before==emu:readRange(0x2002A40,0x4B4),'cancel preserves all save data')
 H.menu(16,10);H.press(1);H.press(0x80);H.press(1)
 H.check(before==emu:readRange(0x2002A40,0x4B4),'A alone cannot apply full completion')
 H.shot('confirmation_requires_shoulder_chord')
 H.press(0x301);H.wait(220);H.close();H.shot('completed_gameplay')
 H.check(H.r8(0x2002A46)==1 and (H.r8(0x2002C9C+(0x55>>3))&(1<<(0x55&7)))~=0,'permanent credits and gameclear flags')
 H.check(H.r8(0x2002A48)==9,'native progress recalculates to endgame9')
 H.check((H.r8(0x2002C9C+(0x51>>3))&(1<<(0x51&7)))==0,'transient ENDING not forced')
 H.check(H.r8(0x2002AEC)==99 and H.r8(0x2002AED)==99,'maximum ammo loaded')
 H.check(H.r8(0x2002AEA)==160 and H.r8(0x2002AEB)==160 and H.r8(0x2002AE9)==0,'20 full hearts and no partial piece')
 H.check(H.r8(0x2002B56)==1 and H.r8(0x2002B57)==100,'native fusion completion counters')
 local fusions=0;for i=1,100 do if (H.r8(0x2002B54+0x12D+(i>>3))&(1<<(i&7)))~=0 then fusions=fusions+1 end end
 H.check(fusions==100,'all100 individual native fusion bits')
 H.check(H.r8(0x2002AF0)==136 and H.item(61)==1 and H.item(62)==1,'136 figures / Tingle Trophy / Carlov Medal')
 local items=true;for i=52,60 do if H.item(i)~=2 then items=false end end
 H.check(items,'consumed quest objects marked handed-in rather than active')
 H.check(emu:readRange(0x2002AC0,6)==name and H.r8(0x2000004)==slot,'name and current save-slot identity preserved')
 local x=H.r32(H.P+44);H.wait(15,0x20);H.wait(8)
 H.check(H.r32(H.P+44)~=x and H.r8(H.S+0x8B)==0,'movement remains available after completion reload')
 H.press(8);H.wait(65);H.shot('native_inventory_completed')
 H.check(H.r8(H.M+4)==7,'native inventory/save opens after completion')
 emu:write8(0x2000083,16);H.wait(5);H.press(1);H.wait(60)
 H.press(0x40);H.press(1);H.wait(180);H.shot('native_save_completed')
 H.press(1);H.wait(60);H.press(8);H.wait(90)
 emu:reset();H.boot()
 H.check(H.r8(H.PM+H.L.menuTheme)==2,'native progress save preserves separate menu settings')
 H.check(H.r8(0x2002A46)==1 and H.r8(0x2002A48)==9 and H.r8(0x2002AEB)==160,'completion survives native save/reset/load')
 H.check(H.r8(0x2002B57)==100 and H.r8(0x2002AF0)==136 and H.item(6)==1,'fusion/figurine/equipment survives native save/load')
 H.menu(16,10);H.shot('completion_after_native_reload');H.close()
 H.check(H.r8(H.M+4)==2,'practice menu still usable after completion save/load')
end)
