local out=assert(os.getenv('TMC_TEST_OUTPUT'))
local H=assert(loadfile(out..'../../tests/gameplay_harness.lua'))()
H.run(function()
 H.action(14,0)
 for _,v in ipairs({{0x22,0x10,88,88,'house'},{0x48,0,120,120,'temple'},{0x80,0,216,256,'castle'}}) do
  H.warp(v[1],v[2],v[3],v[4]);H.wait(40)
  local x,y=H.r32(H.P+44),H.r32(H.P+48)
  local w,h=H.r16(H.R+30),H.r16(H.R+32)
  H.log(v[5]..' action='..H.r8(H.P+12)..' flags='..H.r32(H.S+48)..' floor='..H.r8(H.S+18)..' control='..H.r8(H.S+139)..' size='..w..','..h)
  local sx,sy=H.r16(H.R+10),H.r16(H.R+12)
  H.action(9,4);H.wait(40,0x90);H.shot(v[5]..'_pan')
  H.check(H.r8(H.PM+H.L.cameraActive)==1 and (H.r16(H.R+10)~=sx or H.r16(H.R+12)~=sy),v[5]..' camera visibly pans')
  H.check(H.r32(H.P+44)==x and H.r32(H.P+48)==y,v[5]..' camera does not move Link')
  H.check(H.r16(H.R+30)==w and H.r16(H.R+32)==h,v[5]..' native dimensions never persistently modified')
  H.wait(160,0x190)
  H.check(H.r16(H.R+10)-H.r16(H.R+6)<=784 and H.r16(H.R+12)-H.r16(H.R+8)<=864,v[5]..' viewport remains within loaded 64x64 map')
  H.check(H.r8(H.R+4)==v[1] and H.r8(H.R+5)==v[2],v[5]..' no camera-induced warp')
  H.press(2);H.wait(260);H.shot(v[5]..'_returned')
  H.check(H.r8(H.PM+H.L.cameraActive)==0 and H.r32(H.R+48)==H.P,v[5]..' native camera owner restored')
  H.check(H.r16(H.R+10)==sx and H.r16(H.R+12)==sy,v[5]..' native view returns to original position')
 end
 -- Real scene started through a native transition, no artificial control flags.
 H.warp(3,1,336,272)
 H.log('scene before action='..H.r8(H.P+12)..' ctrl='..H.r8(H.S+139)..' message='..H.r8(0x2000050))
 H.menu(16,2);H.shot('scene_break_free_menu');H.press(1);H.close()
 H.log('scene after status='..emu:readRange(H.PM+H.L.status,28)..' ctrl='..H.r8(H.S+139))
 H.wait(45)
 H.check(H.r8(H.S+139)==0 and (H.r8(0x2000050)&0x7F)==0,'explicit Break Free closes textbox and releases native scene control')
 local x=H.r32(H.P+44);H.wait(24,0x20)
 H.check(H.r32(H.P+44)~=x,'controller movement works after native scene Break Free')
 H.shot('scene_break_free_result')
end)
